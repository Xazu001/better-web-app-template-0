/**
 * Generates a local RS256 key pair (base64 PKCS8 / SPKI) for JWT sessions and
 * writes it into `.dev.vars` — replaces the manual openssl + base64 steps.
 * Deployed envs use `wrangler secret put JWT_PRIVATE_KEY` / `JWT_PUBLIC_KEY`.
 *
 * Run directly: `pnpm gen:keys`. Imported by `scripts/setup.ts`.
 */
import { generateKeyPairSync } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export function generateJwtPair(): {
  JWT_PRIVATE_KEY: string;
  JWT_PUBLIC_KEY: string;
} {
  // With privateKeyEncoding/publicKeyEncoding set, the keys come back as PEM strings.
  const { privateKey, publicKey } = generateKeyPairSync("rsa", {
    modulusLength: 2048,
    privateKeyEncoding: { type: "pkcs8", format: "pem" },
    publicKeyEncoding: { type: "spki", format: "pem" }
  });
  const b64 = (pem: string): string => Buffer.from(pem).toString("base64");
  return {
    JWT_PRIVATE_KEY: b64(privateKey),
    JWT_PUBLIC_KEY: b64(publicKey)
  };
}

export function writeJwtKeys(file: string = ".dev.vars"): void {
  const pair = generateJwtPair();
  const privateLine = `JWT_PRIVATE_KEY=${pair.JWT_PRIVATE_KEY}`;
  const publicLine = `JWT_PUBLIC_KEY=${pair.JWT_PUBLIC_KEY}`;

  let content: string;
  if (existsSync(file)) {
    content = readFileSync(file, "utf8");
    for (const line of [privateLine, publicLine]) {
      const key = line.split("=")[0];
      const re = new RegExp(`^${key}=.*$`, "m");
      content = re.test(content) ? content.replace(re, line) : `${content}\n${line}\n`;
    }
  } else {
    content = `# Generated by \`pnpm gen:keys\` — local dev only, gitignored.\n${privateLine}\n${publicLine}\n`;
  }

  writeFileSync(file, content);
  console.log(`Wrote a fresh JWT key pair to ${file}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeJwtKeys(process.argv[2] ?? ".dev.vars");
}
